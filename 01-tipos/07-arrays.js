// Un array guarda una lista ordenada de elementos.
//Regla mental rápida = ¿Necesito una lista? → Array


let animales = ["chanchito", "caballito"]
console.log(animales)
// Para llamar a un array se llama desde el orden donde se encuentra
console.log(animales[0])
// Agregar mas elemetnos a la variable 
animales [2] = "Dragon"
console.log(animales)
// Ejercicios con espacions, cuando se define un elemento que no respeta el indice de un array 
animales [10] = "pez"
console.log(animales[7])
// Verificar el tipo de dato con typeof y luego se coloca el valor de la variable 
console.log(typeof animales)
// Metodos
console.log(animales.length)

